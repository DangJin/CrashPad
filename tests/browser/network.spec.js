test('300 vehicle desktop benchmark keeps controls responsive and simulation clock current', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'Desktop performance target');
  const config = makeExample(); config.demand.forEach(d => { d.count = 75; d.flow = 120; });
  await page.addInitScript(config => localStorage.setItem('crashpad:network:v1', JSON.stringify({ config })), config);
  await page.goto('/#/traffic/network');
  await page.locator('[data-network-play]').click();
  await expect.poll(async () => Number(await page.locator('.network-stage').getAttribute('data-sim-time'))).toBeGreaterThan(1);
  const start = await page.evaluate(() => ({ wall: performance.now(), sim: Number(document.querySelector('.network-stage').dataset.simTime) }));
  await page.waitForTimeout(8000);
  const end = await page.evaluate(() => ({ wall: performance.now(), sim: Number(document.querySelector('.network-stage').dataset.simTime) }));
  const lag = Math.abs((end.wall - start.wall) / 1000 - (end.sim - start.sim) / 5);
  expect(lag).toBeLessThan(.5);
  const response = await page.evaluate(async () => { const start = performance.now(); document.querySelector('[data-network-play]').click(); await new Promise(resolve => { const frame = () => document.querySelector('[data-network-play]').textContent.includes('继续模拟') ? resolve() : requestAnimationFrame(frame); frame(); }); return performance.now() - start; });
  expect(response).toBeLessThan(200);
  console.info('NETWORK_BENCHMARK', JSON.stringify({ population: 300, rate: 5, lagSeconds: lag, pauseResponseMs: response }));
  await info.attach('benchmark', { body: JSON.stringify({ browser: 'Chrome', viewport: '1440x1100', population: 300, rate: 5, lagSeconds: lag, pauseResponseMs: response }), contentType: 'application/json' });
});
